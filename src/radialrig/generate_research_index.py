#!/usr/bin/env python3
"""Generate research/INDEX.md from the guidance files' frontmatter.

D-32: the guidance files are the only source; every catalog of them is
generated. This script renders the index agents fall back on when the
retrieval tools are absent. The output is generated and never
authoritative (D-07) — the mechanism is the `get_guidance` verb on the
retrieval server, which builds the same catalog live from the same
loader.

An oversized or malformed guidance file is refused, not rendered: the
script prints each refusal and exits non-zero without writing.

From a source checkout it also refreshes the packaged guidance copies
under the package's data/ directory, which answer `get_guidance` on a host
that carries no research tree (PLAN-0005 Phase 1 prescription 4).

Run:  radialrig-index
"""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
from pathlib import Path

from radialrig.doc_core import load_guidance
from radialrig.paths import resolve_root

PILLAR_HEADINGS = {
    "agent-focus": "Agent focus — what a session owes the next session",
    "human-focus": "Human focus — the agent–human relationship",
}

NO_TREE = (
    "no research tree at {root}: nothing to index. This command renders\n"
    "RadialRig's own guidance corpus; a mounted project holds none, and\n"
    "the get_guidance verb answers from the packaged copy there."
)

NO_GUIDANCE = (
    "research/ at {root} holds no guidance files: nothing to index.\n"
    "This command renders RadialRig's own guidance corpus; a project's\n"
    "own research directory stays its own, never indexed here and never\n"
    "overwritten."
)

HEADER = """\
# Research Index

<!-- Generated by src/radialrig/generate_research_index.py (uv run radialrig-index) from the guidance
     files' frontmatter (D-32). Do not edit this file; edit a guidance
     file and regenerate. -->

The agents' file fallback when the retrieval tools are absent. The
mechanism is the `get_guidance` verb on the retrieval server (SPEC-2):
without a topic it returns this catalog, built live from the files;
with a topic it returns that guidance text.

## Corpus convention

- `guidance.md` files are agent-facing rule sets, loaded on demand — these are the operative documents.
- The evidence files beside them are the cited evidence base; open one only to verify or extend a rule, never as background reading.
- Never load more guidance files than the task at hand needs; each one is context you pay for all session.
"""


def render(root: Path) -> str:
    entries, refused = load_guidance(root)
    if refused:
        for r in refused:
            print(f"refused: {r.rel}: {r.reason}", file=sys.stderr)
        raise SystemExit(1)
    parts = [HEADER.rstrip()]
    for pillar in sorted({g.pillar for g in entries}):
        heading = PILLAR_HEADINGS.get(pillar, pillar.replace("-", " ").capitalize())
        parts.append(f"\n## {heading}\n")
        parts.append("| Topic | Load when | Path |\n|---|---|---|")
        for g in entries:
            if g.pillar != pillar:
                continue
            rel = g.rel.removeprefix("research/")
            parts.append(f"| {g.topic} | {g.load_when} | `{rel}` |")
    return "\n".join(parts).rstrip() + "\n"


MANIFEST_NAME = "MANIFEST.json"

DATA_README = """\
Generated copies of research/**/guidance.md, refreshed by radialrig-index.
The live files under research/ hold authority; these copies answer
get_guidance on a host with no research tree (D-32, D-07).
Edit a live guidance file and regenerate; never edit a file here.
"""


def sync_package_data(root: Path, package_dir: Path) -> list[str]:
    """Refresh the packaged guidance copies from the live tree.

    Runs only from a source checkout: the caller proves the target sits
    under root/src/. An installed copy is not a place to write. Copies are
    byte-for-byte, so the drift check is an equality test; a guidance file
    the live tree no longer holds is removed rather than left behind.
    """
    live = root / "research"
    target = package_dir / "data" / "research"
    sources = sorted(live.rglob("guidance.md")) if live.is_dir() else []
    wanted = {p.relative_to(live).as_posix() for p in sources}

    if target.is_dir():
        for stale in sorted(target.rglob("guidance.md")):
            if stale.relative_to(target).as_posix() not in wanted:
                stale.unlink()
    target.mkdir(parents=True, exist_ok=True)

    written: list[str] = []
    entries: list[dict[str, str]] = []
    for source in sources:
        rel = source.relative_to(live).as_posix()
        dest = target / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, dest)
        entries.append({
            "path": f"research/{rel}",
            "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        })
        written.append(f"research/{rel}")

    manifest = {
        "generated_by": "radialrig-index",
        "source": "research/",
        "files": entries,
    }
    # newline="" keeps the LF bytes the recorded hashes are computed
    # over; the platform default would write CRLF on Windows.
    (target / MANIFEST_NAME).write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="",
    )
    (package_dir / "data" / "README.txt").write_text(
        DATA_README, encoding="utf-8", newline="",
    )
    return written


def main() -> None:
    root = resolve_root()
    if not (root / "research").is_dir():
        # A mounted host carries no research tree by design (D-32); refuse
        # in plain words rather than crash on the missing directory, and
        # never create a directory in a host (constraint 5).
        print(NO_TREE.format(root=root), file=sys.stderr)
        raise SystemExit(1)
    if not any(p.is_file() for p in (root / "research").rglob("guidance.md")):
        # A research/ directory with no guidance files is a project's own
        # tree, not this corpus: rendering here would fall back to the
        # packaged copies and overwrite the host's research/INDEX.md with
        # a catalog of files the project does not hold (constraint 5).
        print(NO_GUIDANCE.format(root=root), file=sys.stderr)
        raise SystemExit(1)
    out = root / "research" / "INDEX.md"
    out.write_text(render(root), encoding="utf-8", newline="")
    print(f"wrote {out.relative_to(root).as_posix()}")
    package_dir = Path(__file__).resolve().parent
    if package_dir.is_relative_to(root.resolve() / "src"):
        for rel in sync_package_data(root, package_dir):
            print(f"packaged {rel}")
    else:
        print("packaged corpus not refreshed: not a source checkout")


if __name__ == "__main__":
    main()
