"""Tests for the research index generator (D-32 point 4).

Run:  uv run --with pytest pytest src/radialrig/tests/test_generate_research_index.py -q

The generated INDEX.md is the agents' file fallback when the
retrieval tools are absent, and never authoritative (D-07); these tests hold it to the same source and the
same bound as the get_guidance verb.
"""

from __future__ import annotations

import pytest

from radialrig import generate_research_index as gri
from radialrig.doc_core import GUIDANCE_LINE_BOUND
from radialrig.tests.test_retrieval_server import guidance_text, write


def test_render_derives_rows_from_frontmatter(tmp_path):
    write(tmp_path, "research/agent-focus/context-rot/guidance.md", guidance_text())
    out = gri.render(tmp_path)
    assert "| context-rot | Work runs long. | `agent-focus/context-rot/guidance.md` |" in out
    assert "Do not edit this file" in out
    assert "get_guidance" in out


def test_render_refuses_an_oversized_file(tmp_path, capsys):
    big = "- A rule.\n" * (GUIDANCE_LINE_BOUND + 1)
    write(tmp_path, "research/agent-focus/context-rot/guidance.md",
          guidance_text(body=big))
    with pytest.raises(SystemExit):
        gri.render(tmp_path)
    assert "bound" in capsys.readouterr().err


def test_main_refuses_a_root_without_a_research_tree(tmp_path, monkeypatch, capsys):
    # The mounted-host case from issue #10: no research/ directory at the
    # root. The command refuses in one plain message instead of raising
    # FileNotFoundError, and it creates nothing in the host.
    monkeypatch.setenv("RADIALRIG_DOCS_ROOT", str(tmp_path))
    with pytest.raises(SystemExit) as exc:
        gri.main()
    assert exc.value.code == 1
    err = capsys.readouterr().err
    assert (
        f"no research tree at {tmp_path}: nothing to index. This command renders\n"
        "RadialRig's own guidance corpus; a mounted project holds none, and\n"
        "the get_guidance verb answers from the packaged copy there."
    ) in err
    assert not (tmp_path / "research").exists()


def test_main_refuses_a_projects_own_research_directory(
    tmp_path, monkeypatch, capsys,
):
    # The review's boundary case: a host owns a research/ directory of
    # its own, with no guidance files. The command must refuse rather
    # than overwrite the host's research/INDEX.md with the packaged
    # catalog (constraint 5). Pinned word for word.
    own = tmp_path / "research" / "INDEX.md"
    own.parent.mkdir(parents=True)
    own.write_bytes(b"# Our own research index\n")
    monkeypatch.setenv("RADIALRIG_DOCS_ROOT", str(tmp_path))
    with pytest.raises(SystemExit) as exc:
        gri.main()
    assert exc.value.code == 1
    err = capsys.readouterr().err
    assert (
        f"research/ at {tmp_path} holds no guidance files: nothing to index.\n"
        "This command renders RadialRig's own guidance corpus; a project's\n"
        "own research directory stays its own, never indexed here and never\n"
        "overwritten."
    ) in err
    assert own.read_bytes() == b"# Our own research index\n"


def test_main_refuses_a_directory_named_guidance(tmp_path, monkeypatch, capsys):
    # A directory named guidance.md is not a guidance file. The guard
    # counts files only, so this tree gets the same plain refusal
    # instead of a crash inside the read.
    own = tmp_path / "research" / "INDEX.md"
    own.parent.mkdir(parents=True)
    own.write_bytes(b"# Our own research index\n")
    (tmp_path / "research" / "topic" / "guidance.md").mkdir(parents=True)
    monkeypatch.setenv("RADIALRIG_DOCS_ROOT", str(tmp_path))
    with pytest.raises(SystemExit) as exc:
        gri.main()
    assert exc.value.code == 1
    assert "holds no guidance files" in capsys.readouterr().err
    assert own.read_bytes() == b"# Our own research index\n"


def test_main_renders_a_conforming_tree(tmp_path, monkeypatch, capsys):
    # The success path through both guards, exactly as radialrig-index
    # runs it. A refusal-only pin would let a guard that always refuses
    # pass the whole suite.
    write(tmp_path, "research/agent-focus/context-rot/guidance.md", guidance_text())
    monkeypatch.setenv("RADIALRIG_DOCS_ROOT", str(tmp_path))
    gri.main()
    out = capsys.readouterr().out
    assert "wrote research/INDEX.md" in out
    index = (tmp_path / "research" / "INDEX.md").read_text(encoding="utf-8")
    assert ("| context-rot | Work runs long. | "
            "`agent-focus/context-rot/guidance.md` |") in index


def test_render_ignores_the_existing_index(tmp_path):
    write(tmp_path, "research/INDEX.md", "| phantom | Always | `x` |\n")
    write(tmp_path, "research/agent-focus/context-rot/guidance.md", guidance_text())
    assert "phantom" not in gri.render(tmp_path)


def test_committed_index_matches_a_fresh_render():
    # research/INDEX.md is committed generated output (D-32 point 4).
    # Nothing else compares it with the files it is rendered from, so a
    # guidance edit without `radialrig-index` would drift silently.
    from radialrig.paths import resolve_root

    root = resolve_root()
    if not (root / "research").is_dir():
        pytest.skip("no live research tree at the corpus root")
    committed = (root / "research" / "INDEX.md").read_bytes()
    assert committed == gri.render(root).encode("utf-8")
